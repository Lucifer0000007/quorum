"""Regenerate README sections from source: Cypher from agent/templates.py, numbers from the generated data files."""

import json
import re

from agent.episodic import RECORD_PRECEDENT
from agent.templates import TEMPLATES
from ingest.config import ROOT
from ingest.load import EDGE_QUERIES, NODE_QUERIES

START, END = "<!-- QUERIES:START -->", "<!-- QUERIES:END -->"
S_START, S_END = "<!-- STATS:START -->", "<!-- STATS:END -->"


def _load(rel):
    path = ROOT / rel
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def render_queries() -> str:
    parts = [START, "", "### Agent read templates (`agent/templates.py`, via `GRAPH.RO_QUERY`, 3 s timeout)", ""]
    for name, t in TEMPLATES.items():
        parts += [f"**`{name}`** ({t['graph']} graph): {t['doc']}", "", "```cypher", t["cypher"], "```", ""]
    parts += ["### Approval-gate write (`agent/episodic.py`, graph `agent_episodic_memory` only)", "",
              "```cypher", RECORD_PRECEDENT.strip(), "```", "",
              "### Ingest (`ingest/load.py`, idempotent `UNWIND ... MERGE`, batches of 300)", "", "```cypher"]
    parts += [q.strip() for q in NODE_QUERIES.values()]
    parts += [EDGE_QUERIES["SEE_ALSO"], EDGE_QUERIES["AUTHORED"], "```", "", END]
    return "\n".join(parts)


def render_stats() -> str:
    rep, ver, ev = _load("data/report.json"), _load("data/verdicts.json"), _load("evals/results.json")
    out = [S_START, "", "_Generated by `python -m scripts.render_readme` from `data/report.json`, `data/verdicts.json` "
           "and `evals/results.json`; not typed by hand._", ""]
    if rep:
        st, e = rep["ref_stats"], rep["edge_counts"]
        keyed_by_folder = st.get("ids_without_valid_number", 0) + st.get("ids_from_duplicate_number", 0)
        out += [
            f"- Corpus: kubernetes/enhancements @ `{rep['source_commit'][:12]}`: **{rep['kep_yaml_files']}** kep.yaml "
            f"files, **{len(rep['parse_failures'])}** parse failures, data hash `{rep['data_hash'][:12]}`.",
            f"- Graph: {rep['keps']} KEPs, {rep['people']} people, {len(rep['sigs'])} SIGs; edges "
            + ", ".join(f"{k} {v}" for k, v in e.items()) + ".",
            f"- see-also references: {st.get('see_also_resolved', 0)} resolved to a KEP, "
            f"{st.get('see_also_unresolved', 0)} unresolvable (kept on `KEP.unresolved_refs`), "
            f"{st.get('see_also_placeholder', 0)} placeholders (n/a, TBD). replaces: {st.get('replaces_resolved', 0)} "
            f"resolved / {st.get('replaces_unresolved', 0)} unresolvable. superseded-by: "
            f"{st.get('superseded_by_resolved', 0)} resolved.",
            f"- Cleaning: {st.get('status_normalized', 0)} status values normalized, {st.get('skipped_handles', 0)} "
            f"handles skipped (TBD, empty, team aliases), {keyed_by_folder} KEPs keyed by folder because their "
            f"number is missing or duplicated; prr-approvers non-empty in {rep['fields_non_empty']['prr-approvers']} "
            "files.",
            f"- \"Recent\" threshold: latest-milestone >= v1.{rep['recent_threshold_minor']} (corpus max minus 3).",
        ]
    if ver:
        v = ver["verdicts"]
        out.append(f"- Verdicts over all {ver['keps']} KEPs (live graph): "
                   + ", ".join(f"{k} {n}" for k, n in v.items())
                   + "; rules fired: " + ", ".join(f"{k} {n}" for k, n in ver["rules_fired"].items()) + ".")
        if rep:
            sim = rep["simulation"]["verdicts_min_sigs_2"]
            same = all(sim.get(k) == n for k, n in v.items())
            out.append("- Cross-check: a pure-Python re-implementation over the raw YAML predicts "
                       + ", ".join(f"{k} {n}" for k, n in sim.items()) + (" (identical)." if same else " (DIFFERS)."))
            alt = rep["simulation"]["verdicts_min_sigs_3"]
            out.append("- Threshold sensitivity: requiring 3 SIGs instead of 2 would gate "
                       f"{alt.get('HUMAN_GATE_REQUIRED', 0)} KEPs instead of {sim.get('HUMAN_GATE_REQUIRED', 0)}.")
    if ev:
        out.append(f"- Eval: **{ev['passed']}/{ev['total']} ({ev['rate']:.1%})** questions answered correctly via the "
                   f"keyword router + live graph, run {ev['ran_at']} on data `{ev['data_hash'][:12]}`; by kind: "
                   + ", ".join(f"{k} {x['passed']}/{x['total']}" for k, x in ev["by_kind"].items()) + ".")
    out += ["", S_END]
    return "\n".join(out)


def main():
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    for start, end, block in ((START, END, render_queries()), (S_START, S_END, render_stats())):
        if start not in text:
            raise SystemExit(f"README is missing the {start} marker")
        text = re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _, b=block: b, text, flags=re.DOTALL)
    readme.write_text(text, encoding="utf-8")
    print(f"README regenerated: {len(TEMPLATES)} templates + stats")


if __name__ == "__main__":
    main()
