"""Regenerate README sections from source: Cypher from agent/templates.py, numbers from the generated data files."""

import json
import re

from agent.episodic import RECORD_PRECEDENT
from agent.templates import TEMPLATES
from ingest.config import ROOT
from ingest.load import EDGE_QUERIES, NODE_QUERIES

START, END = "<!-- QUERIES:START -->", "<!-- QUERIES:END -->"
S_START, S_END = "<!-- STATS:START -->", "<!-- STATS:END -->"
L_START, L_END = "<!-- LLM:START -->", "<!-- LLM:END -->"
V_START, V_END = "<!-- VERDICTS:START -->", "<!-- VERDICTS:END -->"
E_START, E_END = "<!-- EVAL:START -->", "<!-- EVAL:END -->"


def _load(rel):
    path = ROOT / rel
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def render_queries() -> str:
    parts = [START, "", "### Agent read templates (`agent/templates.py`, via `GRAPH.RO_QUERY`, 3 s timeout)", ""]
    for name, t in TEMPLATES.items():
        parts += [f"**`{name}`** ({t['graph']} graph): {t['doc']}", "", "```cypher", t["cypher"], "```", ""]
    parts += ["### Approval-gate write (`agent/episodic.py`, graph `agent_episodic_memory` only)", "",
              "```cypher", RECORD_PRECEDENT.strip(), "```", "",
              "### Ingest (`ingest/load.py`, idempotent `UNWIND ... MERGE`, batches of 300)", "", "```cypher"]
    parts += [q.strip() for q in NODE_QUERIES.values()]
    parts += [EDGE_QUERIES["SEE_ALSO"], EDGE_QUERIES["AUTHORED"], "```", "", END]
    return "\n".join(parts)


def render_stats() -> str:
    rep, ver, ev = _load("data/report.json"), _load("data/verdict_report.json"), _load("evals/results.json")
    out = [S_START, "", "_Generated by `python -m scripts.render_readme` from `data/report.json`, "
           "`data/verdict_report.json` and `evals/results.json`; not typed by hand._", ""]
    if rep:
        st, e = rep["ref_stats"], rep["edge_counts"]
        keyed_by_folder = st.get("ids_without_valid_number", 0) + st.get("ids_from_duplicate_number", 0)
        out += [
            f"- Corpus: kubernetes/enhancements @ `{rep['source_commit'][:12]}`: **{rep['kep_yaml_files']}** kep.yaml "
            f"files, **{len(rep['parse_failures'])}** parse failures, data hash `{rep['data_hash'][:12]}`.",
            f"- Graph: {rep['keps']} KEPs, {rep['people']} people, {len(rep['sigs'])} SIGs; edges "
            + ", ".join(f"{k} {v}" for k, v in e.items()) + ".",
            f"- see-also references: {st.get('see_also_resolved', 0)} resolved to a KEP, "
            f"{st.get('see_also_unresolved', 0)} unresolvable (kept on `KEP.unresolved_refs`), "
            f"{st.get('see_also_placeholder', 0)} placeholders (n/a, TBD). replaces: {st.get('replaces_resolved', 0)} "
            f"resolved / {st.get('replaces_unresolved', 0)} unresolvable. superseded-by: "
            f"{st.get('superseded_by_resolved', 0)} resolved.",
            f"- Cleaning: {st.get('status_normalized', 0)} status values normalized, {st.get('skipped_handles', 0)} "
            f"handles skipped (TBD, empty, team aliases), {keyed_by_folder} KEPs keyed by folder because their "
            f"number is missing or duplicated; prr-approvers non-empty in {rep['fields_non_empty']['prr-approvers']} "
            "files.",
            f"- \"Recent\" threshold: latest-milestone >= v1.{rep['recent_threshold_minor']} (corpus max minus 3).",
        ]
    if ver:
        v = ver["verdicts"]
        out.append(f"- Verdicts over all {ver['kep_count']} KEPs (live graph): "
                   + ", ".join(f"{k} {n}" for k, n in v.items()) + " (rule breakdown in the verdict section).")
        if rep:
            sim = rep["simulation"]["verdicts_min_sigs_2"]
            same = all(sim.get(k) == n for k, n in v.items())
            out.append("- Cross-check: a pure-Python re-implementation over the raw YAML predicts "
                       + ", ".join(f"{k} {n}" for k, n in sim.items()) + (" (identical)." if same else " (DIFFERS)."))
            alt = rep["simulation"]["verdicts_min_sigs_3"]
            out.append("- Threshold sensitivity: requiring 3 SIGs instead of 2 would gate "
                       f"{alt.get('HUMAN_GATE_REQUIRED', 0)} KEPs instead of {sim.get('HUMAN_GATE_REQUIRED', 0)}.")
    if ev:
        out.append(f"- Eval run {ev['ran_at']} on data `{ev['data_hash'][:12]}`: results in the section at the top.")
    out += ["", S_END]
    return "\n".join(out)


def _eval_table(suite: dict) -> list[str]:
    head = ["| Question kind | Questions | Query layer correct | Keyword search correct | Tie (both correct) "
            "| Query layer only | Keyword search only | Both wrong |", "|---|---|---|---|---|---|---|---|"]

    def row(label: str, s: dict) -> str:
        o = s["outcomes"]
        return (f"| {label} | {s['total']} | {s['query_layer_correct']} | {s['keyword_correct']} | {o['tie']} "
                f"| {o['query_layer_only']} | {o['keyword_only']} | {o['both_wrong']} |")

    return head + [row(f"`{k}`", s) for k, s in suite["by_kind"].items()] + [row("**All**", suite)]


def render_eval() -> str:
    """Eval results, straight from evals/results.json (python -m evals.run_eval). Multi-hop leads; lookups follow."""
    ev = _load("evals/results.json")
    out = [E_START, ""]
    if not ev:
        return "\n".join(out + ["_Run `make eval` to generate the results._", "", E_END])
    mh, lk = ev["suites"]["multihop"], ev["suites"]["lookups"]
    failed = [r["id"] for s in (mh, lk) for r in s["questions"] if not r["query_layer"]["ok"]]
    kw_only = [r["id"] for s in (mh, lk) for r in s["questions"] if r["outcome"] == "keyword_only"]
    out += [
        f"Every question below was answered by two systems and scored against gold answers computed from the raw YAML "
        f"alone (no FalkorDB, no `ingest/`). Run {ev['ran_at']} on data `{ev['data_hash'][:12]}`, corpus commit "
        f"`{str(ev['corpus_commit'])[:12]}`; reproduce with `make eval`.", "",
        "- **Query layer**: Quorum, i.e. typed queries over the FalkorDB graph.",
        "- **Keyword search**: a one-pass keyword search over the raw kep.yaml text (`evals/baseline.py`). It is a "
        "plain text baseline, not a strong retrieval system: it never goes past the first hop and applies none of the "
        "cleaning rules (SIG aliases, status normalization, team aliases). A stronger baseline, such as iterated "
        "searches or a model reading the files, could close part of the gap.", "",
        "### Multi-hop questions", "",
        "These need paths: everything reachable via see-also/replaces within 2 or 3 hops, the active KEPs reachable "
        "from a withdrawn, rejected or replaced KEP, and the SIGs that own them. \"Reachable via see-also/replaces\" "
        "means exactly that; a link is not a claim that one KEP depends on another.", "",
        *_eval_table(mh), "",
        "### Lookups (a baseline)", "",
        "Single-fact questions (owner, status, successor, referrers, counts, approvers). A keyword search can answer "
        "most of these, so they check that the graph agrees with the files rather than show an advantage.", "",
        *_eval_table(lk), "",
        f"Query-layer failures: {', '.join(failed) if failed else 'none'}. Questions only the keyword search got "
        f"right: {', '.join(kw_only) if kw_only else 'none'}. Per-question answers, gold and errors for both systems "
        "are in `evals/results.json`.",
        "", E_END,
    ]
    return "\n".join(out)


def render_verdicts() -> str:
    """How the bailiff's rules behave over every KEP, from data/verdict_report.json (scripts/verdict_report.py)."""
    from agent.bailiff import RULES

    rep = _load("data/verdict_report.json")
    out = [V_START, ""]
    if not rep:
        out.append("_Run `make verdicts` to generate the verdict report._")
        return "\n".join(out + ["", V_END])
    n, hops, v = rep["kep_count"], rep["hops"], rep["verdicts"]
    allm, first, sens = rep["rules_all_match"], rep["rules_first_match"], rep["hop_sensitivity"]
    out += [
        f"`python -m scripts.verdict_report` runs the bailiff over all {n} KEPs of the live graph (data "
        f"`{rep['data_hash'][:12]}`, gate at {rep['min_sigs_for_gate']}+ SIGs, {hops} hops):", "",
        "| Verdict | KEPs |", "|---|---|",
        *[f"| `{k}` | {v.get(k, 0)} |" for k in ("CLEAN", "AT_RISK", "HUMAN_GATE_REQUIRED")], "",
        f"Rules fired. *All-match* counts every rule that fired on a KEP, so it can add up to more than {n}; "
        f"*first-match* gives each KEP to the first rule that fired in the order R1, R2, R3, R4 (CLEAN if none), so it "
        f"adds up to {n}.", "",
        "| Rule | Name | All-match | First-match |", "|---|---|---|---|",
        *[f"| {r} | {RULES[r][0]} | {allm.get(r, 0)} | {first.get(r, 0)} |" for r in RULES], "",
        "Sensitivity to the hop threshold (the same rules, with reach limited to 1, 2 or 3 hops):", "",
        "| Hops | CLEAN | AT_RISK | HUMAN_GATE_REQUIRED | KEPs with any KEP in reach |", "|---|---|---|---|---|",
        *[f"| {h} | {sens[h]['verdicts'].get('CLEAN', 0)} | {sens[h]['verdicts'].get('AT_RISK', 0)} | "
          f"{sens[h]['verdicts'].get('HUMAN_GATE_REQUIRED', 0)} | {sens[h]['keps_with_reach']} |"
          for h in sorted(sens, key=int)], "",
        "Why the split looks like this, from the numbers above:",
        f"- {rep['no_reach']} of {n} KEPs have no REPLACES/SEE_ALSO path to any KEP within {hops} hops, so nothing is "
        "reachable from them; such a KEP is CLEAN unless R4 fires on it (no recently active approver). "
        f"CLEAN is {v.get('CLEAN', 0)}.",
        f"- Links concentrate on a few hub KEPs: only {n - rep['no_reach']} KEPs reach anything, and the largest "
        f"reach from one KEP is {rep['largest_reach']} KEPs"
        + (" (some reach was cut off at LIMIT 100)." if rep.get("reach_capped") else "."),
        f"- The gate is sensitive to the hop threshold: {sens['1']['verdicts'].get('HUMAN_GATE_REQUIRED', 0)} KEPs "
        f"reach 2+ SIGs through direct links alone, {sens[str(hops)]['verdicts'].get('HUMAN_GATE_REQUIRED', 0)} within "
        f"{hops} hops. We kept {hops} because it is the radius the blast-radius query reports; that is a choice, not a "
        "finding.",
        (f"- R3 is the first rule to fire on {first.get('R3', 0)} KEPs: every KEP that references a stale KEP "
         "already has an active KEP in reach, so R1 or R2 fires before it. It still shows up as extra evidence on "
         f"{allm.get('R3', 0)} verdicts." if not first.get("R3", 0) else
         f"- R3 fires first on {first.get('R3', 0)} KEPs and appears on {allm.get('R3', 0)} verdicts overall."),
        f"- {rep['reasons_have_evidence']['with_evidence']} of {rep['reasons_have_evidence']['total']} reasons carry "
        "the rule name, the query id, the matched ids and the exact Cypher.",
        "", V_END,
    ]
    return "\n".join(out)


def render_llm() -> str:
    """The LLM facts, straight from the smoke-test evidence file (nothing here is typed by hand)."""
    smoke = _load("evals/llm_smoke.json")
    out = [L_START, ""]
    if not smoke:
        out.append("- Smoke test: **not run**. No LLM has been verified, so the default mode is Keywords only.")
    else:
        t = smoke["totals"]
        where = "against the real API" if smoke.get("real_api") else "against a stub, NOT the real API"
        verdict = "LLM" if smoke["passed"] else "Keywords only (the smoke test did not fully pass)"
        out += [
            f"- Provider and model tested: **{smoke['provider']}**, `{smoke['model']}` "
            "(OpenAI-compatible chat completions with tool calling).",
            f"- Smoke test (`python -m scripts.llm_smoke`), run {where} on {smoke['ran_at']}: "
            f"**{t['pass']} passed, {t['fail']} failed, {t['rate_limited']} rate limited** of {t['questions']} "
            "questions (`evals/llm_smoke.json`).",
            f"- Mode for anyone who configures exactly this provider and model: {verdict}. With any other "
            "configuration, or none, the default is Keywords only until the smoke test has passed for it.",
        ]
    out += ["", L_END]
    return "\n".join(out)


def main():
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    for start, end, block in ((START, END, render_queries()), (S_START, S_END, render_stats()),
                             (L_START, L_END, render_llm()), (V_START, V_END, render_verdicts()),
                             (E_START, E_END, render_eval())):
        if start not in text:
            raise SystemExit(f"README is missing the {start} marker")
        text = re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _, b=block: b, text, flags=re.DOTALL)
    readme.write_text(text, encoding="utf-8", newline="\n")
    print(f"README regenerated: {len(TEMPLATES)} templates + stats")


if __name__ == "__main__":
    main()
